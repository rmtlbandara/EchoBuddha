import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const distDir = path.join(root, "dist");
const output = path.join(root, "src/data/monetization-route-registry.mjs");

const candidatePaths = new Set([
  "/articles/buddhist-wisdom-for-overthinking/",
  "/articles/compassion-with-boundaries/",
  "/articles/dhamma-vs-dharma/",
  "/articles/dhammapada-reflection-what-we-think/",
  "/articles/dhammapada-verse-1-meaning/",
  "/articles/noble-eightfold-path-practical-guide/",
  "/articles/right-speech-buddhism/"
]);

function walk(directory) {
  return fs.readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const absolute = path.join(directory, entry.name);
    return entry.isDirectory() ? walk(absolute) : [absolute];
  });
}

function routeFor(file) {
  const relative = path.relative(distDir, file).split(path.sep).join("/");
  if (relative === "index.html") return "/";
  if (relative === "404.html") return "/404.html";
  if (relative.endsWith("/index.html")) return `/${relative.slice(0, -"index.html".length)}`;
  return `/${relative.replace(/\.html$/, "")}/`;
}

function familyFor(route) {
  if (route === "/") return "HOME";
  if (route === "/404.html") return "ERROR";
  if (/^\/articles\/[^/]+\/$/.test(route)) return "ARTICLE";
  if (route.startsWith("/articles/")) return "ARTICLE_NAVIGATION";
  if (route.startsWith("/learn/buddhist-dictionary/")) return "DICTIONARY";
  if (/^\/learn\/[^/]+\/[^/]+\/$/.test(route) || ["/learn/buddhism-for-beginners/", "/learn/eightfold-path/", "/learn/four-noble-truths/"].includes(route)) return "LEARN_DETAIL";
  if (route.startsWith("/learn/")) return "LEARN_NAVIGATION";
  if (route.startsWith("/quotes/")) return "QUOTE";
  if (route.startsWith("/daily-reflections/")) return "DAILY_REFLECTION";
  if (route.startsWith("/meditation/")) return "MEDITATION";
  if (["/about/", "/authors/echo-buddha-editorial/", "/buddhist-sources-and-citations/", "/corrections/", "/editorial-policy/", "/how-echo-buddha-creates-content/", "/meditation-safety/", "/quote-attribution-policy/"].includes(route)) return "TRUST";
  if (["/disclaimer/", "/privacy-policy/", "/terms-of-use/"].includes(route)) return "LEGAL";
  if (["/contact/", "/search/", "/tools/"].includes(route) || route.startsWith("/tools/")) return "UTILITY";
  return "OTHER";
}

function policyFor(route, html) {
  const noindex = /<meta[^>]+name=["']robots["'][^>]+content=["'][^"']*noindex/i.test(html)
    || /<meta[^>]+content=["'][^"']*noindex[^"']*["'][^>]+name=["']robots["']/i.test(html);
  const family = familyFor(route);

  if (candidatePaths.has(route)) {
    return { state: "ELIGIBLE_CANDIDATE", family, indexable: true, reason: "EXPLICIT_PHASE_6_MATERIALLY_UPGRADED_ARTICLE" };
  }
  if (noindex) return { state: "NEVER_MONETIZE", family, indexable: false, reason: "NOINDEX_OR_USER_SPECIFIC_ROUTE" };
  if (family === "ARTICLE" || family === "LEARN_DETAIL") {
    return { state: "HOLD_MANUAL_REVIEW", family, indexable: true, reason: "INDEXABLE_SUBSTANTIVE_ROUTE_NOT_EXPLICITLY_APPROVED" };
  }
  return { state: "NEVER_MONETIZE", family, indexable: true, reason: "FAMILY_EXCLUDED_OR_NON_SUBSTANTIVE_SCREEN" };
}

if (!fs.existsSync(distDir)) throw new Error("dist/ is required; run npm run build before generating the Phase 10 route registry");

const registry = Object.fromEntries(
  walk(distDir)
    .filter((file) => file.endsWith(".html"))
    .map((file) => {
      const route = routeFor(file);
      return [route, policyFor(route, fs.readFileSync(file, "utf8"))];
    })
    .sort(([a], [b]) => a.localeCompare(b))
);

const body = `// Generated by scripts/generate-phase-10-route-registry.mjs.\n// Unknown routes are deliberately absent and fail closed in monetization.mjs.\nexport const MONETIZATION_ROUTE_REGISTRY = ${JSON.stringify(registry, null, 2)};\n`;
fs.writeFileSync(output, body);
console.log(JSON.stringify({ output: path.relative(root, output), routes: Object.keys(registry).length }, null, 2));
